//! `generate --scaffold-profiles DIR`: a provider-profile skeleton for every credential no profile declares.
//!
//! The skeleton is built from the `egress` directives that sit in the same file as the `provider` directive (hosts, ports,
//! `access`, binaries), so it starts out matching what the code does. It is a starting point: review the auth style, the
//! endpoints and the binaries, then check it with `openshell provider profile lint -f`.

use crate::config::Config;
use crate::directive::{Directive, Kind};
use crate::generate::find_bin;
use crate::providers::Unmapped;
use std::collections::BTreeSet;

/// One generated file.
#[derive(Debug, Clone)]
pub struct Skeleton {
    pub id: String,
    pub file_name: String,
    pub yaml: String,
    pub endpoints: usize,
}

/// Profile id for a credential variable: lower case, `_` -> `-` (`CONTEXT7_API_KEY` -> `context7-api-key`).
pub fn profile_id(env: &str) -> String {
    env.to_ascii_lowercase().replace('_', "-")
}

fn q(s: &str) -> String {
    serde_json::to_string(s).unwrap()
}

pub fn scaffold(unmapped: &[Unmapped], dirs: &[Directive], cfg: &Config) -> Vec<Skeleton> {
    let bins: Vec<&Directive> = dirs
        .iter()
        .filter(|d| matches!(d.kind, Kind::Bin { .. }))
        .collect();
    let mut out = Vec::new();
    for u in unmapped {
        // files that declare this credential (config-declared credentials have no file)
        let files: BTreeSet<String> = u
            .sources
            .iter()
            .filter_map(|s| s.rsplit_once(':'))
            .filter(|(_, line)| line.parse::<usize>().is_ok())
            .map(|(f, _)| f.to_string())
            .collect();
        let mut endpoints: Vec<(String, u16, Option<String>, bool)> = Vec::new();
        let mut binaries: BTreeSet<String> = BTreeSet::new();
        for d in dirs.iter().filter(|d| files.contains(&d.file)) {
            let Kind::Egress { host, ports } = &d.kind else {
                continue;
            };
            if let Ok((b, _)) = find_bin(d, &bins, cfg) {
                binaries.insert(b);
            }
            for p in ports {
                let e = (
                    host.clone(),
                    *p,
                    d.attr("access").map(str::to_string),
                    d.attr("tls") == Some("skip"),
                );
                if !endpoints.iter().any(|x| x.0 == e.0 && x.1 == e.1) {
                    endpoints.push(e);
                }
            }
        }
        let id = profile_id(&u.env);
        let name = u.env.to_ascii_lowercase();
        let mut y = String::new();
        y.push_str(&format!(
            "# Skeleton generated by openshell-annotate for {} (used at {}).\n",
            u.env,
            u.sources.join(", ")
        ));
        y.push_str("# Review before importing: auth style and header, the endpoints, and `binaries` (the paths in YOUR image).\n");
        y.push_str("# Check it:   openshell provider profile lint -f <this file>\n");
        y.push_str("# Import it:  openshell provider profile import -f <this file> --global\n");
        y.push_str(&format!("id: {id}\n"));
        y.push_str(&format!("display_name: {}\n", q(&u.env)));
        y.push_str(&format!(
            "description: {}\n",
            q(&format!("Credential {} read by the application", u.env))
        ));
        y.push_str("category: other\n");
        y.push_str("credentials:\n");
        y.push_str(&format!("  - name: {name}\n"));
        y.push_str(&format!(
            "    description: {}\n",
            q(&format!("{} value", u.env))
        ));
        y.push_str(&format!("    env_vars: [{}]\n", u.env));
        y.push_str("    required: true\n");
        y.push_str("    # TODO: how does the API take this credential? bearer (authorization header) is the common case.\n");
        y.push_str("    auth_style: bearer\n");
        y.push_str("    header_name: authorization\n");
        y.push_str("discovery:\n");
        y.push_str(&format!("  credentials: [{name}]\n"));
        if endpoints.is_empty() {
            y.push_str("# TODO: no egress directive in the file that declares this credential: list the hosts it is sent to.\n");
            y.push_str("endpoints: []\n");
        } else {
            y.push_str("endpoints:\n");
            for (host, port, access, skip) in &endpoints {
                y.push_str(&format!("  - host: {}\n    port: {port}\n", q(host)));
                if *skip {
                    y.push_str("    # tls=skip on the egress directive: relayed without inspection (no protocol or access rules), so\n");
                    y.push_str("    # OpenShell requires the credential on an L4-only endpoint to be allowed explicitly.\n");
                    y.push_str("    allow_uninspected_credentials: true\n");
                } else {
                    y.push_str("    protocol: rest\n");
                    y.push_str(&format!(
                        "    access: {}\n",
                        access.as_deref().unwrap_or("read-write")
                    ));
                    y.push_str("    enforcement: enforce\n");
                }
            }
        }
        if binaries.is_empty() {
            y.push_str("# TODO: name the binaries that may use these endpoints (real paths in the image).\n");
            y.push_str("binaries: []\n");
        } else {
            y.push_str(&format!(
                "binaries: [{}]\n",
                binaries.iter().map(|b| q(b)).collect::<Vec<_>>().join(", ")
            ));
        }
        out.push(Skeleton {
            file_name: format!("{id}.yaml"),
            id,
            yaml: y,
            endpoints: endpoints.len(),
        });
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ids_are_lower_case_with_hyphens() {
        assert_eq!(profile_id("CONTEXT7_API_KEY"), "context7-api-key");
        assert_eq!(profile_id("UPSTREAM_API_KEY"), "upstream-api-key");
    }
}
