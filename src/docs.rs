//! Reproducible reference docs: `docs/CLI.md` (from the clap command tree) and `docs/DIRECTIVES.md` (from `spec.rs`).

use crate::spec;
use anyhow::{bail, Context, Result};
use std::path::Path;

/// Strip trailing whitespace so output is stable across clap versions' padding.
fn clean(s: &str) -> String {
    s.lines().map(str::trim_end).collect::<Vec<_>>().join("\n")
}

/// Renders the long help of `cmd` without colour at a fixed 100-column width, so the text does not depend on the
/// terminal it is generated in.
fn help_of(cmd: &clap::Command) -> String {
    let mut c = cmd
        .clone()
        .term_width(100)
        .max_term_width(100)
        .color(clap::ColorChoice::Never);
    clean(&c.render_long_help().to_string())
}

/// `docs/CLI.md`: the help of the root command and of every subcommand.
///
/// Hidden subcommands are skipped.
pub fn cli_md(root: &clap::Command) -> String {
    let mut s = String::new();
    s.push_str("# CLI reference\n\n");
    s.push_str("<!-- Generated by `openshell-annotate docs` from the clap definitions. Do not edit; run `scripts/gen-docs.sh`. -->\n\n");
    let name = root.get_name().to_string();
    s.push_str(&format!("## `{name}`\n\n```text\n{}\n```\n", help_of(root)));
    for sub in root.get_subcommands().filter(|c| !c.is_hide_set()) {
        s.push_str(&format!(
            "\n## `{name} {}`\n\n```text\n{}\n```\n",
            sub.get_name(),
            help_of(&sub.clone().bin_name(format!("{name} {}", sub.get_name())))
        ));
    }
    s
}

/// All generated files: (file name, content).
pub fn generate(root: &clap::Command) -> Vec<(&'static str, String)> {
    vec![
        ("CLI.md", cli_md(root)),
        ("DIRECTIVES.md", spec::directives_md()),
    ]
}

/// Write the generated docs into `dir`.
///
/// Creates `dir` if needed and returns the paths of the files written.
///
/// # Errors
///
/// Fails when `dir` cannot be created or a file in it cannot be written.
pub fn write(root: &clap::Command, dir: &Path) -> Result<Vec<String>> {
    std::fs::create_dir_all(dir).with_context(|| format!("creating {}", dir.display()))?;
    let mut out = Vec::new();
    for (name, body) in generate(root) {
        let p = dir.join(name);
        std::fs::write(&p, body).with_context(|| format!("writing {}", p.display()))?;
        out.push(p.display().to_string());
    }
    Ok(out)
}

/// Fail (with the stale file names) when the committed docs differ from what the code generates.
///
/// # Errors
///
/// Fails when any generated file in `dir` is missing, unreadable or differs from the generated content.
pub fn check(root: &clap::Command, dir: &Path) -> Result<()> {
    let mut stale = Vec::new();
    for (name, body) in generate(root) {
        let p = dir.join(name);
        match std::fs::read_to_string(&p) {
            Ok(have) if have == body => {}
            _ => stale.push(p.display().to_string()),
        }
    }
    if stale.is_empty() {
        Ok(())
    } else {
        bail!("generated docs are stale: {}; regenerate with `openshell-annotate docs` (scripts/gen-docs.sh)", stale.join(", "))
    }
}
